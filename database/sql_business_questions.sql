-- Q01. How many active customers does the platform currently have, by country?
SELECT c.country,
       COUNT(DISTINCT s.customer_id) AS active_customers
FROM subscriptions s
JOIN customers c ON c.customer_id = s.customer_id
WHERE s.subscription_status = 'Active'
GROUP BY c.country
ORDER BY active_customers DESC, c.country;

-- Q02. What is the total and average monthly revenue generated by each subscription plan?
SELECT sp.plan_name,
       ROUND(SUM(s.monthly_price), 2) AS total_monthly_revenue,
       ROUND(AVG(s.monthly_price), 2) AS average_monthly_revenue
FROM subscriptions s
JOIN subscription_plans sp ON sp.plan_id = s.plan_id
WHERE s.subscription_status = 'Active'
GROUP BY sp.plan_name
ORDER BY total_monthly_revenue DESC;

-- Q03. What is the overall churn rate (percentage of customers with churned = true)?
SELECT COUNT(*) AS customers,
       COUNT(*) FILTER (WHERE churned = true) AS churned_customers,
       ROUND(100.0 * COUNT(*) FILTER (WHERE churned = true) / COUNT(*), 2) AS churn_rate_pct
FROM churn_labels;

-- Q04. Which acquisition channel has brought in the most customers, and what is the churn rate for each channel?
SELECT c.acquisition_channel,
       COUNT(*) AS n_customers,
       COUNT(*) FILTER (WHERE cl.churned) AS churned_customers,
       ROUND(100.0 * COUNT(*) FILTER (WHERE cl.churned) / COUNT(*), 2) AS churn_rate_pct
FROM customers c
JOIN churn_labels cl ON cl.customer_id = c.customer_id
GROUP BY c.acquisition_channel
ORDER BY n_customers DESC, c.acquisition_channel;

-- Q05. What is the average customer age by subscription plan?
WITH latest_subscription AS (
    SELECT DISTINCT ON (customer_id)
           customer_id,
           plan_id
    FROM subscriptions
    ORDER BY customer_id, subscription_start_date DESC, subscription_id DESC
)
SELECT sp.plan_name,
       ROUND(AVG(c.age), 2) AS average_age,
       COUNT(*) AS customers
FROM latest_subscription ls
JOIN customers c ON c.customer_id = ls.customer_id
JOIN subscription_plans sp ON sp.plan_id = ls.plan_id
GROUP BY sp.plan_name
ORDER BY sp.plan_name;

-- Q06. List the top 10 most-watched titles by total watch_duration_minutes.
SELECT c.title,
       SUM(v.watch_duration_minutes) AS total_watch_minutes
FROM viewing_activity v
JOIN content c ON c.content_id = v.content_id
GROUP BY c.title
ORDER BY total_watch_minutes DESC, c.title
LIMIT 10;

-- Q07. What is the average completion_percentage by content_type and genre?
SELECT c.content_type,
       c.genre,
       ROUND(AVG(v.completion_percentage), 2) AS avg_completion_percentage,
       COUNT(*) AS sessions
FROM viewing_activity v
JOIN content c ON c.content_id = v.content_id
GROUP BY c.content_type, c.genre
ORDER BY c.content_type, avg_completion_percentage DESC;

-- Q08. How many failed payments occurred in each of the last 12 months?
WITH bounds AS (
    SELECT DATE_TRUNC('month', MAX(payment_date))::date AS end_month
    FROM payments
),
months AS (
    SELECT generate_series(
               (SELECT end_month FROM bounds) - INTERVAL '11 months',
               (SELECT end_month FROM bounds),
               INTERVAL '1 month'
           )::date AS month_start
)
SELECT TO_CHAR(m.month_start, 'YYYY-MM') AS month,
       COUNT(p.payment_id) AS failed_payments
FROM months m
LEFT JOIN payments p
       ON LOWER(p.payment_status) = 'failed'
      AND DATE_TRUNC('month', p.payment_date)::date = m.month_start
GROUP BY m.month_start
ORDER BY m.month_start;

-- Q09. What is the average resolution_time_hours by issue_category?
