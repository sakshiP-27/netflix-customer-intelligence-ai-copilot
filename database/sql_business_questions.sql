-- Netflix Customer Intelligence — 37 business questions
-- Windows such as "last 12 months" and "last 90 days" are measured from the
-- latest date in the relevant table. The extract ends in June 2026, so using
-- today's date would drop those windows off the end of the data.
-- Successful revenue is payment_status = Success. Churn is churn_labels.churned.

