-- Q28. Customers with 2+ failed payments in the last 90 days who are flagged as
-- high churn risk. This database has no churn_risk_score column, so the flag
-- used here is churn_labels.churned. Current plan is the latest subscription.
WITH bounds AS (
    SELECT MAX(payment_date) AS as_of
    FROM payments
),
failed AS (
    SELECT p.customer_id,
           COUNT(*) AS failed_payment_count
    FROM payments p
    CROSS JOIN bounds b
    WHERE LOWER(p.payment_status) = 'failed'
      AND p.payment_date > b.as_of - INTERVAL '90 days'
      AND p.payment_date <= b.as_of
    GROUP BY p.customer_id
    HAVING COUNT(*) >= 2
),
current_plan AS (
    SELECT DISTINCT ON (s.customer_id)
           s.customer_id,
           sp.plan_name
    FROM subscriptions s
    JOIN subscription_plans sp ON sp.plan_id = s.plan_id
    ORDER BY s.customer_id, s.subscription_start_date DESC, s.subscription_id DESC
)
SELECT f.customer_id,
       f.failed_payment_count,
       cp.plan_name AS current_plan
FROM failed f
JOIN churn_labels cl ON cl.customer_id = f.customer_id AND cl.churned
JOIN current_plan cp ON cp.customer_id = f.customer_id
ORDER BY f.failed_payment_count DESC, f.customer_id;

-- Q29. Average watch minutes per session in the 30 days before and after each
-- customer's most recent subscription price change, and the percentage change.
WITH ordered_subs AS (
    SELECT s.customer_id,
           s.subscription_start_date AS change_date,
           sp.monthly_price,
           LAG(sp.monthly_price) OVER (
               PARTITION BY s.customer_id
               ORDER BY s.subscription_start_date, s.subscription_id
           ) AS previous_price
    FROM subscriptions s
    JOIN subscription_plans sp ON sp.plan_id = s.plan_id
),
latest_change AS (
    SELECT DISTINCT ON (customer_id)
           customer_id,
           change_date
    FROM ordered_subs
    WHERE previous_price IS NOT NULL
      AND monthly_price IS DISTINCT FROM previous_price
    ORDER BY customer_id, change_date DESC
),
engagement AS (
    SELECT ch.customer_id,
           ch.change_date,
           AVG(v.watch_duration_minutes) FILTER (
               WHERE v.viewing_date >= ch.change_date - INTERVAL '30 days'
                 AND v.viewing_date < ch.change_date
           ) AS avg_minutes_before,
           AVG(v.watch_duration_minutes) FILTER (
               WHERE v.viewing_date >= ch.change_date
                 AND v.viewing_date < ch.change_date + INTERVAL '30 days'
           ) AS avg_minutes_after
    FROM latest_change ch
    LEFT JOIN viewing_activity v ON v.customer_id = ch.customer_id
    GROUP BY ch.customer_id, ch.change_date
)
SELECT customer_id,
       change_date,
       ROUND(avg_minutes_before, 2) AS avg_minutes_before,
       ROUND(avg_minutes_after, 2) AS avg_minutes_after,
       ROUND(100.0 * (avg_minutes_after - avg_minutes_before) / NULLIF(avg_minutes_before, 0), 2) AS pct_change
FROM engagement
ORDER BY customer_id;

-- Q30. For each country: customers, churned customers, churn rate, average lifetime
-- value of churned customers, and the top churn reason.
WITH customer_spend AS (
    SELECT customer_id,
           COALESCE(SUM(amount) FILTER (WHERE LOWER(payment_status) = 'success'), 0) AS lifetime_spend
    FROM payments
    GROUP BY customer_id
),
country_base AS (
    SELECT c.country,
           c.customer_id,
           cl.churned,
           cl.churn_reason,
           COALESCE(cs.lifetime_spend, 0) AS lifetime_spend
    FROM customers c
    JOIN churn_labels cl ON cl.customer_id = c.customer_id
    LEFT JOIN customer_spend cs ON cs.customer_id = c.customer_id
),
country_stats AS (
    SELECT country,
           COUNT(*) AS total_customers,
           COUNT(*) FILTER (WHERE churned) AS churned_customers,
           ROUND(100.0 * COUNT(*) FILTER (WHERE churned) / COUNT(*), 2) AS churn_rate_pct,
           ROUND(AVG(lifetime_spend) FILTER (WHERE churned), 2) AS avg_clv_churned_customers
    FROM country_base
    GROUP BY country
),
reason_counts AS (
    SELECT country,
           churn_reason,
           COUNT(*) AS reason_count,
           ROW_NUMBER() OVER (
               PARTITION BY country
               ORDER BY COUNT(*) DESC, churn_reason
           ) AS reason_rank
    FROM country_base
    WHERE churned
      AND churn_reason IS NOT NULL
    GROUP BY country, churn_reason
)
SELECT s.country,
       s.total_customers,
       s.churned_customers,
       s.churn_rate_pct,
       s.avg_clv_churned_customers,
       r.churn_reason AS top_churn_reason
FROM country_stats s
LEFT JOIN reason_counts r
       ON r.country = s.country
      AND r.reason_rank = 1
ORDER BY s.churn_rate_pct DESC, s.country;

-- Q31. At-risk revenue for currently active customers. The score is the average of
-- min-max normalized days since last activity, failed-payment rate, and support-ticket count.
WITH as_of AS (
    SELECT MAX(viewing_date) AS as_of
    FROM viewing_activity
),
active AS (
    SELECT customer_id, monthly_price
    FROM subscriptions
    WHERE subscription_status = 'Active'
),
last_view AS (
    SELECT customer_id, MAX(viewing_date) AS last_view_date
    FROM viewing_activity
    GROUP BY customer_id
),
pay AS (
    SELECT customer_id,
           COUNT(*) FILTER (WHERE LOWER(payment_status) = 'failed')::numeric
               / NULLIF(COUNT(*), 0) AS failed_payment_rate
    FROM payments
    GROUP BY customer_id
),
tickets AS (
    SELECT customer_id, COUNT(*) AS support_ticket_count
    FROM support_tickets
    GROUP BY customer_id
),
features AS (
    SELECT a.customer_id,
           a.monthly_price,
           ((SELECT as_of FROM as_of) - COALESCE(lv.last_view_date, c.registration_date)) AS days_since_last_activity,
           COALESCE(p.failed_payment_rate, 0) AS failed_payment_rate,
           COALESCE(t.support_ticket_count, 0) AS support_ticket_count
    FROM active a
    JOIN customers c ON c.customer_id = a.customer_id
    LEFT JOIN last_view lv ON lv.customer_id = a.customer_id
    LEFT JOIN pay p ON p.customer_id = a.customer_id
    LEFT JOIN tickets t ON t.customer_id = a.customer_id
),
bounds AS (
    SELECT MIN(days_since_last_activity) AS min_days,
           MAX(days_since_last_activity) AS max_days,
           MIN(failed_payment_rate) AS min_fail,
           MAX(failed_payment_rate) AS max_fail,
           MIN(support_ticket_count) AS min_tickets,
           MAX(support_ticket_count) AS max_tickets
    FROM features
),
scored AS (
    SELECT f.customer_id,
           f.monthly_price,
           f.days_since_last_activity,
           f.failed_payment_rate,
           f.support_ticket_count,
           (
               COALESCE((f.days_since_last_activity - b.min_days)::numeric / NULLIF(b.max_days - b.min_days, 0), 0)
               + COALESCE((f.failed_payment_rate - b.min_fail) / NULLIF(b.max_fail - b.min_fail, 0), 0)
               + COALESCE((f.support_ticket_count - b.min_tickets)::numeric / NULLIF(b.max_tickets - b.min_tickets, 0), 0)
           ) / 3 AS risk_score
    FROM features f
    CROSS JOIN bounds b
)
SELECT customer_id,
       days_since_last_activity,
       ROUND(failed_payment_rate, 4) AS failed_payment_rate,
       support_ticket_count,
       ROUND(risk_score, 4) AS risk_score,
       ROUND(risk_score * monthly_price, 2) AS at_risk_revenue
FROM scored
ORDER BY at_risk_revenue DESC, customer_id
LIMIT 50;

-- Q32. Top 5 issue_subcategory values per country for the most recent completed quarter,
-- with average resolution time and average satisfaction.
WITH as_of AS (
    SELECT MAX(ticket_date) AS max_date
    FROM support_tickets
),
quarter_bounds AS (
    SELECT CASE
               WHEN (SELECT max_date FROM as_of)
                    >= (DATE_TRUNC('quarter', (SELECT max_date FROM as_of)) + INTERVAL '3 months' - INTERVAL '1 day')::date
               THEN DATE_TRUNC('quarter', (SELECT max_date FROM as_of))::date
               ELSE (DATE_TRUNC('quarter', (SELECT max_date FROM as_of)) - INTERVAL '3 months')::date
           END AS quarter_start
),
quarter_tickets AS (
    SELECT c.country,
           t.issue_subcategory,
           t.resolution_time_hours,
           t.customer_satisfaction_score
    FROM support_tickets t
    JOIN customers c ON c.customer_id = t.customer_id
    CROSS JOIN quarter_bounds q
    WHERE t.ticket_date >= q.quarter_start
      AND t.ticket_date < q.quarter_start + INTERVAL '3 months'
),
subcategory_stats AS (
    SELECT country,
           issue_subcategory,
           COUNT(*) AS ticket_count,
           ROUND(AVG(resolution_time_hours), 2) AS avg_resolution_hours,
           ROUND(AVG(customer_satisfaction_score), 2) AS avg_satisfaction
    FROM quarter_tickets
    GROUP BY country, issue_subcategory
),
ranked AS (
    SELECT country,
           issue_subcategory,
           ticket_count,
           avg_resolution_hours,
           avg_satisfaction,
           ROW_NUMBER() OVER (
               PARTITION BY country
               ORDER BY ticket_count DESC, issue_subcategory
           ) AS subcategory_rank
    FROM subcategory_stats
)
SELECT (SELECT quarter_start FROM quarter_bounds) AS quarter_start,
       country,
       subcategory_rank,
       issue_subcategory,
       ticket_count,
       avg_resolution_hours,
       avg_satisfaction
FROM ranked
WHERE subcategory_rank <= 5
ORDER BY country, subcategory_rank;

-- Q33. Win-back candidates: churned customers whose pre-churn lifetime value is in the top quartile.
WITH pre_churn_spend AS (
    SELECT cl.customer_id,
           cl.churn_date,
           cl.churn_reason,
           COALESCE(SUM(p.amount) FILTER (
               WHERE LOWER(p.payment_status) = 'success'
                 AND p.payment_date <= cl.churn_date
           ), 0) AS lifetime_value_before_churn
    FROM churn_labels cl
    LEFT JOIN payments p ON p.customer_id = cl.customer_id
    WHERE cl.churned
    GROUP BY cl.customer_id, cl.churn_date, cl.churn_reason
),
quartiles AS (
    SELECT customer_id,
           churn_date,
           churn_reason,
           lifetime_value_before_churn,
           NTILE(4) OVER (ORDER BY lifetime_value_before_churn, customer_id) AS value_quartile
    FROM pre_churn_spend
),
engagement AS (
    SELECT q.customer_id,
           COALESCE(SUM(v.watch_duration_minutes), 0) AS watch_minutes_last_30_days
    FROM quartiles q
    LEFT JOIN viewing_activity v
           ON v.customer_id = q.customer_id
          AND v.viewing_date > q.churn_date - INTERVAL '30 days'
          AND v.viewing_date <= q.churn_date
    WHERE q.value_quartile = 4
    GROUP BY q.customer_id
)
SELECT q.customer_id,
       q.churn_reason,
       ROUND(q.lifetime_value_before_churn, 2) AS lifetime_value_before_churn,
       e.watch_minutes_last_30_days AS last_known_engagement_minutes
FROM quartiles q
JOIN engagement e ON e.customer_id = q.customer_id
WHERE q.value_quartile = 4
ORDER BY q.lifetime_value_before_churn DESC, q.customer_id;

-- Q34. Most common plan-migration path, and whether upgraders churn differently from downgraders.
WITH ordered_subs AS (
    SELECT s.customer_id,
           s.subscription_start_date,
           s.subscription_id,
           sp.plan_name,
           sp.monthly_price,
           ROW_NUMBER() OVER (
               PARTITION BY s.customer_id
               ORDER BY s.subscription_start_date, s.subscription_id
           ) AS sub_order,
           COUNT(*) OVER (PARTITION BY s.customer_id) AS sub_count
    FROM subscriptions s
    JOIN subscription_plans sp ON sp.plan_id = s.plan_id
),
moves AS (
    SELECT a.customer_id,
           a.plan_name AS from_plan,
           b.plan_name AS to_plan,
           CASE
               WHEN b.monthly_price > a.monthly_price THEN 'upgrade'
               WHEN b.monthly_price < a.monthly_price THEN 'downgrade'
               ELSE 'lateral'
           END AS direction
    FROM ordered_subs a
    JOIN ordered_subs b
      ON b.customer_id = a.customer_id
     AND b.sub_order = a.sub_order + 1
    WHERE a.plan_name <> b.plan_name
),
path_counts AS (
    SELECT from_plan,
           to_plan,
           COUNT(*) AS n_migrations
    FROM moves
    GROUP BY from_plan, to_plan
),
customer_direction AS (
    SELECT customer_id,
           CASE
               WHEN LAST_VALUE(monthly_price) OVER (
                        PARTITION BY customer_id
                        ORDER BY subscription_start_date, subscription_id
                        ROWS BETWEEN UNBOUNDED PRECEDING AND UNBOUNDED FOLLOWING
                    )
                    > FIRST_VALUE(monthly_price) OVER (
                        PARTITION BY customer_id
                        ORDER BY subscription_start_date, subscription_id
                    )
               THEN 'upgrade'
               WHEN LAST_VALUE(monthly_price) OVER (
                        PARTITION BY customer_id
                        ORDER BY subscription_start_date, subscription_id
                        ROWS BETWEEN UNBOUNDED PRECEDING AND UNBOUNDED FOLLOWING
                    )
                    < FIRST_VALUE(monthly_price) OVER (
                        PARTITION BY customer_id
                        ORDER BY subscription_start_date, subscription_id
                    )
               THEN 'downgrade'
               ELSE 'lateral'
           END AS net_direction
    FROM ordered_subs
    WHERE sub_count > 1
),
one_direction AS (
    SELECT DISTINCT customer_id, net_direction
    FROM customer_direction
),
direction_churn AS (
    SELECT d.net_direction,
           ROUND(100.0 * AVG(CASE WHEN cl.churned THEN 1 ELSE 0 END), 2) AS churn_rate_pct
    FROM one_direction d
    JOIN churn_labels cl ON cl.customer_id = d.customer_id
    GROUP BY d.net_direction
)
SELECT p.from_plan,
       p.to_plan,
       p.n_migrations,
       u.churn_rate_pct AS upgrader_churn_rate_pct,
       d.churn_rate_pct AS downgrader_churn_rate_pct
FROM path_counts p
LEFT JOIN direction_churn u ON u.net_direction = 'upgrade'
LEFT JOIN direction_churn d ON d.net_direction = 'downgrade'
ORDER BY p.n_migrations DESC, p.from_plan, p.to_plan;

-- Q35. Weekly and monthly active users over the last 6 months, and the WAU/MAU stickiness ratio.
WITH bounds AS (
    SELECT DATE_TRUNC('month', MAX(viewing_date))::date AS end_month
    FROM viewing_activity
),
months AS (
    SELECT generate_series(
               (SELECT end_month FROM bounds) - INTERVAL '5 months',
               (SELECT end_month FROM bounds),
               INTERVAL '1 month'
           )::date AS month_start
),
weekly_users AS (
    SELECT DATE_TRUNC('month', DATE_TRUNC('week', viewing_date))::date AS month_start,
           DATE_TRUNC('week', viewing_date)::date AS week_start,
           COUNT(DISTINCT customer_id) AS wau
    FROM viewing_activity
    GROUP BY 1, 2
),
avg_wau AS (
    SELECT month_start,
           ROUND(AVG(wau), 1) AS avg_wau
    FROM weekly_users
    GROUP BY month_start
),
mau AS (
    SELECT DATE_TRUNC('month', viewing_date)::date AS month_start,
           COUNT(DISTINCT customer_id) AS mau
    FROM viewing_activity
    GROUP BY 1
)
SELECT m.month_start,
       w.avg_wau,
       mau.mau,
       ROUND(w.avg_wau / NULLIF(mau.mau, 0), 4) AS stickiness_ratio
FROM months m
JOIN avg_wau w ON w.month_start = m.month_start
JOIN mau ON mau.month_start = m.month_start
ORDER BY m.month_start;

-- Q36. Customers who left negative feedback within 14 days of a failed payment
-- or a support ticket with satisfaction <= 2.
WITH negative_feedback AS (
    SELECT customer_id, feedback_date
    FROM customer_feedback
    WHERE sentiment_label = 'Negative'
),
triggers AS (
    SELECT customer_id, payment_date AS event_date, 'failed_payment' AS trigger_type
    FROM payments
    WHERE LOWER(payment_status) = 'failed'
    UNION ALL
    SELECT customer_id, ticket_date, 'low_satisfaction_ticket'
    FROM support_tickets
    WHERE customer_satisfaction_score <= 2
),
matches AS (
    SELECT f.customer_id,
           f.feedback_date,
           t.trigger_type
    FROM negative_feedback f
    JOIN triggers t
      ON t.customer_id = f.customer_id
     AND f.feedback_date BETWEEN t.event_date - INTERVAL '14 days'
                              AND t.event_date + INTERVAL '14 days'
)
SELECT customer_id,
       MIN(feedback_date) AS first_negative_feedback_date,
       STRING_AGG(DISTINCT trigger_type, ', ' ORDER BY trigger_type) AS outreach_trigger
FROM matches
GROUP BY customer_id
ORDER BY customer_id;

-- Q37. Customer health score from 0 to 100. Higher health is better. risk_score is
-- 100 minus health, so the riskiest customers come first.
WITH as_of AS (
    SELECT MAX(viewing_date) AS as_of
    FROM viewing_activity
),
latest_plan AS (
    SELECT DISTINCT ON (s.customer_id)
           s.customer_id,
           sp.plan_name,
           s.monthly_price
    FROM subscriptions s
    JOIN subscription_plans sp ON sp.plan_id = s.plan_id
    ORDER BY s.customer_id, s.subscription_start_date DESC, s.subscription_id DESC
),
last_view AS (
    SELECT customer_id, MAX(viewing_date) AS last_view_date
    FROM viewing_activity
    GROUP BY customer_id
),
pay AS (
    SELECT customer_id,
           COUNT(*) FILTER (WHERE LOWER(payment_status) = 'failed')::numeric
               / NULLIF(COUNT(*), 0) AS failed_payment_rate
    FROM payments
    GROUP BY customer_id
),
support AS (
    SELECT customer_id,
           AVG(customer_satisfaction_score) AS avg_support_satisfaction
    FROM support_tickets
    WHERE customer_satisfaction_score IS NOT NULL
    GROUP BY customer_id
),
features AS (
    SELECT c.customer_id,
           lp.plan_name AS current_plan,
           lp.monthly_price,
           ((SELECT as_of FROM as_of) - COALESCE(lv.last_view_date, c.registration_date)) AS days_since_last_view,
           COALESCE(p.failed_payment_rate, 0) AS payment_failure_rate,
           s.avg_support_satisfaction,
           ((SELECT as_of FROM as_of) - c.registration_date) AS tenure_days
    FROM customers c
    JOIN latest_plan lp ON lp.customer_id = c.customer_id
    LEFT JOIN last_view lv ON lv.customer_id = c.customer_id
    LEFT JOIN pay p ON p.customer_id = c.customer_id
    LEFT JOIN support s ON s.customer_id = c.customer_id
),
filled AS (
    SELECT customer_id,
           current_plan,
           monthly_price,
           days_since_last_view,
           payment_failure_rate,
           COALESCE(avg_support_satisfaction, (SELECT AVG(avg_support_satisfaction) FROM features)) AS avg_support_satisfaction,
           tenure_days
    FROM features
),
bounds AS (
    SELECT MIN(days_since_last_view) AS min_recency,
           MAX(days_since_last_view) AS max_recency,
           MIN(payment_failure_rate) AS min_fail,
           MAX(payment_failure_rate) AS max_fail,
           MIN(avg_support_satisfaction) AS min_csat,
           MAX(avg_support_satisfaction) AS max_csat,
           MIN(tenure_days) AS min_tenure,
           MAX(tenure_days) AS max_tenure,
           MIN(monthly_price) AS min_price,
           MAX(monthly_price) AS max_price
    FROM filled
),
scored AS (
    SELECT f.customer_id,
           f.current_plan,
           f.days_since_last_view,
           ROUND(f.payment_failure_rate, 4) AS payment_failure_rate,
           ROUND(f.avg_support_satisfaction, 2) AS avg_support_satisfaction,
           f.tenure_days,
           ROUND(
               100 * (
                   (1 - COALESCE((f.days_since_last_view - b.min_recency)::numeric / NULLIF(b.max_recency - b.min_recency, 0), 0))
                   + (1 - COALESCE((f.payment_failure_rate - b.min_fail) / NULLIF(b.max_fail - b.min_fail, 0), 0))
                   + COALESCE((f.avg_support_satisfaction - b.min_csat) / NULLIF(b.max_csat - b.min_csat, 0), 0)
                   + COALESCE((f.tenure_days - b.min_tenure)::numeric / NULLIF(b.max_tenure - b.min_tenure, 0), 0)
                   + COALESCE((f.monthly_price - b.min_price) / NULLIF(b.max_price - b.min_price, 0), 0)
               ) / 5,
               2
           ) AS health_score
    FROM filled f
    CROSS JOIN bounds b
)
SELECT customer_id,
       current_plan,
       days_since_last_view,
       payment_failure_rate,
       avg_support_satisfaction,
       tenure_days,
       health_score,
       ROUND(100 - health_score, 2) AS risk_score
FROM scored
ORDER BY risk_score DESC, customer_id;
