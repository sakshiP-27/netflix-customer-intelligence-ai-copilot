-- Q26. Using a CTE, compute each customer's lifetime spend and rank customers into quartiles with NTILE(4).
WITH lifetime_spend AS (
    SELECT c.customer_id,
           COALESCE(SUM(p.amount) FILTER (WHERE LOWER(p.payment_status) = 'success'), 0) AS lifetime_spend
    FROM customers c
    LEFT JOIN payments p ON p.customer_id = c.customer_id
    GROUP BY c.customer_id
)
SELECT customer_id,
       ROUND(lifetime_spend, 2) AS lifetime_spend,
       NTILE(4) OVER (ORDER BY lifetime_spend, customer_id) AS spend_quartile
FROM lifetime_spend
ORDER BY spend_quartile DESC, lifetime_spend DESC, customer_id;

