-- Q16. Using RANK(), rank subscription plans by total revenue generated
-- (monthly_price x count of active subscriptions).
SELECT sp.plan_name,
       sp.monthly_price,
       COUNT(s.subscription_id) AS active_subscriptions,
       sp.monthly_price * COUNT(s.subscription_id) AS total_revenue,
       RANK() OVER (
           ORDER BY sp.monthly_price * COUNT(s.subscription_id) DESC
       ) AS revenue_rank
FROM subscription_plans sp
LEFT JOIN subscriptions s
       ON s.plan_id = sp.plan_id
      AND s.subscription_status = 'Active'
GROUP BY sp.plan_id, sp.plan_name, sp.monthly_price
ORDER BY revenue_rank, sp.plan_name;

-- Q17. For each customer, use ROW_NUMBER() to identify their most recent support ticket and return only that row.
WITH ranked_tickets AS (
    SELECT ticket_id,
           customer_id,
           ticket_date,
           issue_category,
           issue_subcategory,
           priority,
           ticket_status,
           resolution_time_hours,
           customer_satisfaction_score,
           ROW_NUMBER() OVER (
               PARTITION BY customer_id
               ORDER BY ticket_date DESC, ticket_id DESC
           ) AS ticket_recency
    FROM support_tickets
)
SELECT ticket_id,
       customer_id,
       ticket_date,
       issue_category,
       issue_subcategory,
       priority,
       ticket_status,
       resolution_time_hours,
       customer_satisfaction_score
FROM ranked_tickets
WHERE ticket_recency = 1
ORDER BY customer_id;

-- Q18. Calculate a 3-month moving average of new customer registrations using a window function.
WITH monthly_signups AS (
    SELECT DATE_TRUNC('month', registration_date)::date AS month_start,
           COUNT(*) AS new_customers
    FROM customers
    GROUP BY 1
)
SELECT month_start,
       new_customers,
       ROUND(AVG(new_customers) OVER (
           ORDER BY month_start
           ROWS BETWEEN 2 PRECEDING AND CURRENT ROW
       ), 2) AS moving_avg_3_months
FROM monthly_signups
ORDER BY month_start;

-- Q19. Using LAG(), identify customers whose monthly watch time in the most recent
-- month is lower than their watch time in the prior month.
WITH monthly_watch AS (
    SELECT customer_id,
           DATE_TRUNC('month', viewing_date)::date AS month_start,
           SUM(watch_duration_minutes) AS watch_minutes
    FROM viewing_activity
    GROUP BY customer_id, month_start
),
with_prior AS (
    SELECT customer_id,
           month_start,
           watch_minutes,
           LAG(month_start) OVER (
               PARTITION BY customer_id ORDER BY month_start
           ) AS prior_month,
           LAG(watch_minutes) OVER (
               PARTITION BY customer_id ORDER BY month_start
           ) AS prior_watch_minutes
    FROM monthly_watch
),
latest_month AS (
    SELECT MAX(month_start) AS month_start
    FROM monthly_watch
)
SELECT w.customer_id,
       w.month_start AS recent_month,
       w.watch_minutes AS recent_watch_minutes,
       w.prior_watch_minutes
FROM with_prior w
JOIN latest_month lm ON lm.month_start = w.month_start
WHERE w.prior_month = (w.month_start - INTERVAL '1 month')::date
  AND w.watch_minutes < w.prior_watch_minutes
ORDER BY (w.prior_watch_minutes - w.watch_minutes) DESC, w.customer_id;

-- Q20. Customer acquisition cohort analysis: group by registration month, and show
-- what percentage of each cohort is still active at 1, 3, and 6 months.
WITH bounds AS (
    SELECT MAX(churn_date) AS as_of
    FROM churn_labels
),
cohorts AS (
    SELECT c.customer_id,
           DATE_TRUNC('month', c.registration_date)::date AS cohort_month,
           c.registration_date,
           cl.churn_date
    FROM customers c
    JOIN churn_labels cl ON cl.customer_id = c.customer_id
)
SELECT cohort_month,
       COUNT(*) AS cohort_size,
       ROUND(100.0 * AVG(CASE
           WHEN registration_date + INTERVAL '1 month' > (SELECT as_of FROM bounds) THEN NULL
           WHEN churn_date IS NULL OR churn_date > registration_date + INTERVAL '1 month' THEN 1
           ELSE 0
       END), 2) AS pct_active_after_1_month,
       ROUND(100.0 * AVG(CASE
           WHEN registration_date + INTERVAL '3 months' > (SELECT as_of FROM bounds) THEN NULL
           WHEN churn_date IS NULL OR churn_date > registration_date + INTERVAL '3 months' THEN 1
           ELSE 0
       END), 2) AS pct_active_after_3_months,
       ROUND(100.0 * AVG(CASE
           WHEN registration_date + INTERVAL '6 months' > (SELECT as_of FROM bounds) THEN NULL
           WHEN churn_date IS NULL OR churn_date > registration_date + INTERVAL '6 months' THEN 1
           ELSE 0
       END), 2) AS pct_active_after_6_months
FROM cohorts
GROUP BY cohort_month
ORDER BY cohort_month;

-- Q21. Using DENSE_RANK(), rank countries by churn rate and return only the top 5.
WITH country_churn AS (
    SELECT c.country,
           ROUND(100.0 * AVG(CASE WHEN cl.churned THEN 1 ELSE 0 END), 2) AS churn_rate_pct,
           COUNT(*) AS customers
    FROM customers c
    JOIN churn_labels cl ON cl.customer_id = c.customer_id
    GROUP BY c.country
),
ranked AS (
    SELECT country,
           customers,
           churn_rate_pct,
           DENSE_RANK() OVER (ORDER BY churn_rate_pct DESC, country) AS churn_rank
    FROM country_churn
)
SELECT churn_rank, country, customers, churn_rate_pct
FROM ranked
WHERE churn_rank <= 5
ORDER BY churn_rank, country;

-- Q22. For every customer, compute a running total of payments made, ordered by payment_date.
SELECT customer_id,
       payment_id,
       payment_date,
       amount,
       SUM(amount) OVER (
           PARTITION BY customer_id
           ORDER BY payment_date, payment_id
           ROWS BETWEEN UNBOUNDED PRECEDING AND CURRENT ROW
       ) AS running_total_paid
FROM payments
WHERE LOWER(payment_status) = 'success'
ORDER BY customer_id, payment_date, payment_id;

-- Q23. Identify customers whose watch time declined for three consecutive months
-- (month N < month N-1 < month N-2).
WITH monthly_watch AS (
    SELECT customer_id,
           DATE_TRUNC('month', viewing_date)::date AS month_start,
           SUM(watch_duration_minutes) AS watch_minutes
    FROM viewing_activity
    GROUP BY customer_id, month_start
),
streaks AS (
    SELECT customer_id,
           month_start,
           watch_minutes,
           LAG(watch_minutes, 1) OVER (PARTITION BY customer_id ORDER BY month_start) AS minutes_n1,
           LAG(watch_minutes, 2) OVER (PARTITION BY customer_id ORDER BY month_start) AS minutes_n2,
           LAG(month_start, 1) OVER (PARTITION BY customer_id ORDER BY month_start) AS month_n1,
           LAG(month_start, 2) OVER (PARTITION BY customer_id ORDER BY month_start) AS month_n2
    FROM monthly_watch
)
SELECT DISTINCT customer_id
FROM streaks
WHERE month_n1 = (month_start - INTERVAL '1 month')::date
  AND month_n2 = (month_start - INTERVAL '2 months')::date
  AND minutes_n2 > minutes_n1
  AND minutes_n1 > watch_minutes
ORDER BY customer_id;

-- Q24. Monthly churn rate over the last 12 months
-- (churned customers in month X / active customers at the start of month X).
WITH bounds AS (
    SELECT DATE_TRUNC('month', MAX(churn_date))::date AS end_month
    FROM churn_labels
),
months AS (
    SELECT generate_series(
               (SELECT end_month FROM bounds) - INTERVAL '11 months',
               (SELECT end_month FROM bounds),
               INTERVAL '1 month'
           )::date AS month_start
),
base AS (
    SELECT c.customer_id, c.registration_date, cl.churn_date
    FROM customers c
    JOIN churn_labels cl ON cl.customer_id = c.customer_id
)
SELECT m.month_start,
       COUNT(*) FILTER (
           WHERE b.registration_date < m.month_start
             AND (b.churn_date IS NULL OR b.churn_date >= m.month_start)
       ) AS active_at_month_start,
       COUNT(*) FILTER (
           WHERE b.churn_date >= m.month_start
             AND b.churn_date < m.month_start + INTERVAL '1 month'
       ) AS churned_in_month,
       ROUND(
           100.0 * COUNT(*) FILTER (
               WHERE b.churn_date >= m.month_start
                 AND b.churn_date < m.month_start + INTERVAL '1 month'
           )
           / NULLIF(COUNT(*) FILTER (
               WHERE b.registration_date < m.month_start
                 AND (b.churn_date IS NULL OR b.churn_date >= m.month_start)
           ), 0),
           2
       ) AS monthly_churn_rate_pct
FROM months m
CROSS JOIN base b
GROUP BY m.month_start
ORDER BY m.month_start;

-- Q25. Retention rate by acquisition_channel: of customers acquired through each channel, what percentage are still active today?
SELECT c.acquisition_channel,
